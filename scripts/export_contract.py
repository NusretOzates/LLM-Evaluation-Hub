"""Export deterministic API models to TypeScript and check for transport drift."""

import argparse
import json
from pathlib import Path
from typing import Any

from fastapi import FastAPI

from llm_evaluation_hub.api.import_routes import router as import_router
from llm_evaluation_hub.api.inference_routes import router as inference_router
from llm_evaluation_hub.api.routes import router

ROOT = Path(__file__).resolve().parents[1]


def ts_type(schema: dict[str, Any]) -> str:  # noqa: PLR0911
    """Translate the JSON Schema constructs emitted by these API models."""
    if "$ref" in schema:
        return str(schema["$ref"]).split("/")[-1].replace("-", "_")
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(item) for item in schema[key])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            required = schema.get("required", [])
            fields = [
                f"  {json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
                for name, value in schema["properties"].items()
            ]
            return "{\n" + "\n".join(fields) + "\n}"
        additional = schema.get("additionalProperties", {})
        return (
            "{ [key: string]: "
            + (ts_type(additional) if isinstance(additional, dict) else "unknown")
            + " }"
        )
    types = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind in types:
        return types[kind]
    if not set(schema) - {"title", "description", "default", "examples"}:
        return "unknown"
    raise ValueError(f"unsupported transport schema: {schema}")


def main() -> None:
    """Generate the contract, or fail when checked-in output differs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    application = FastAPI()
    application.include_router(router)
    application.include_router(import_router)
    application.include_router(inference_router)
    models = application.openapi()["components"]["schemas"]
    text = "// Generated by scripts/export_contract.py. Do not edit.\n\n"
    text += (
        "\n\n".join(
            f"export type {name.replace('-', '_')} = {ts_type(schema)};"
            for name, schema in sorted(models.items())
        )
        + "\n"
    )
    if "JsonValue-Output" in models:
        text += "\nexport type JsonValue = JsonValue_Output;\n"
    target = ROOT / "web/app/api-schema.ts"
    if args.check:
        if not target.is_file() or target.read_text() != text:
            raise SystemExit("API types are stale. Run uv run python scripts/export_contract.py")
    else:
        target.write_text(text)


if __name__ == "__main__":
    main()
